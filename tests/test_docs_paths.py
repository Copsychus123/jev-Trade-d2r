"""Verify that all file paths referenced in README.md and AGENTS.md exist."""

import re
from pathlib import Path


def extract_doc_paths():
    """
    Extract all backticked file paths from README.md and AGENTS.md.
    Returns set of relative paths that should exist.
    Skips glob patterns (containing *) and tokens with ellipsis (...).
    """
    repo_root = Path(__file__).resolve().parents[1]  # this file lives in tests/
    paths = set()
    
    # Pattern: backticked token that starts with scripts/, src/, core/, services/, or extension/
    # and contains a file extension (.py, .js, .md, .json, .mjs, .html, .css)
    # May end with :function or :123-style suffix (which we strip)
    pattern = r"`((?:scripts|src|core|services|extension)/[^`]*\.(?:py|js|md|json|mjs|html|css)(?::[a-zA-Z0-9_\-]+)?)`"
    
    for doc_file in ["README.md", "AGENTS.md"]:
        doc_path = repo_root / doc_file
        if not doc_path.exists():
            continue
        
        content = doc_path.read_text(encoding="utf-8")
        
        # Find all backticked tokens
        matches = re.findall(pattern, content)
        for match in matches:
            # Strip any :function or :123 suffix
            path_str = match.split(":")[0]
            
            # Skip if it contains ... (ellipsis/truncation indicator) or * (glob patterns)
            if "..." in path_str or "*" in path_str:
                continue
            
            paths.add(path_str)
    
    return paths


def test_all_doc_paths_exist():
    """Assert that every file path referenced in docs exists."""
    repo_root = Path(__file__).resolve().parents[1]  # this file lives in tests/
    doc_paths = extract_doc_paths()
    # A wrong root (a moved test file) or a broken pattern would make this test pass without checking anything.
    for doc_file in ("README.md", "AGENTS.md"):
        assert (repo_root / doc_file).is_file(), f"{doc_file} was not found at {repo_root}"
    assert doc_paths, "no backticked paths were extracted from README.md/AGENTS.md"
    
    # Allow-list for git-ignored but valid generated/build/cache paths
    # These are generated on demand; allow if they don't exist yet
    allow_list = {
        "services/.build/app.py",  # Generated by services/build.py
        "services/.build/jevsvc/app.py",  # Generated by services/build.py
        "extension/dist",  # Generated by extension/build.py
        "scripts/data/item_pairs.json",  # Generated cache from build_item_tables.py full run
    }
    
    missing = []
    for path_str in sorted(doc_paths):
        full_path = repo_root / path_str
        if not full_path.exists() and path_str not in allow_list:
            missing.append(path_str)
    
    assert not missing, f"Stale paths in README.md/AGENTS.md: {missing}"


def test_every_shipped_module_is_named_in_the_rulebook():
    """A module the rulebook never names is a behaviour with no address: a reader cannot find where it lives, and a
    rename or a delete of it goes unnoticed (a documented path is checked by the test above, an undocumented one is
    not). `extension/src/vendor` and the item tables are data, not modules."""
    repo_root = Path(__file__).resolve().parents[1]
    rulebook = (repo_root / "AGENTS.md").read_text(encoding="utf-8")
    skip = ("vendor", "data", "__pycache__", "dist", ".build", ".tmp")
    modules = [
        path
        for base, suffix in (
            (repo_root / "extension" / "src", ".js"),
            (repo_root / "src" / "jev_ultrafast", ".py"),
            (repo_root / "services" / "jevsvc", ".py"),
        )
        for path in base.rglob(f"*{suffix}")
        if path.is_file()
        and path.name != "__init__.py"
        and not any(part in skip for part in path.parts)
    ]
    assert len(modules) >= 50, f"only {len(modules)} modules were found; the walk is broken"
    unnamed = sorted(path.relative_to(repo_root).as_posix() for path in modules if path.name not in rulebook)
    assert not unnamed, f"modules no document names: {unnamed}"


# Variables of the platform or of a tool we call, not settings of this project: the WSGI transport's, the OS paths
# (the Chrome profile and a per-user install), the e2e script's subprocess, browser_harness's own.
PLATFORM_ENV = {
    "CONTENT_LENGTH",
    "HTTP_",
    "PATH_INFO",
    "REMOTE_ADDR",
    "LOCALAPPDATA",
    "XDG_DATA_HOME",
    "PYTHONPATH",
    "BU_CDP_URL",
}
ENV_READERS = (
    r"""os\.environ(?:\.get)?\s*[\[(]\s*['"]?([A-Z][A-Z0-9_]{3,})""",
    r"""getenv\(\s*['"]?([A-Z][A-Z0-9_]{3,})""",
    r"""process\.env\.([A-Z][A-Z0-9_]{3,})""",
    # config.py reads its keys through get_clean/number/price, chrome.py through env.get: the names are literals there
    r"""(?:get_clean|env\.get|environ\.get|os\.getenv|number|price)\(\s*['"]([A-Z][A-Z0-9_]{3,})['"]""",
)


def test_every_setting_the_code_reads_is_documented():
    """A setting nobody documents is a knob the operator cannot find. This found two: CHROME_PATH (which the error
    message itself tells the user to set) and API_RETRY_COUNT (which `.env.example` listed every neighbour of)."""
    repo_root = Path(__file__).resolve().parents[1]
    docs = "\n".join(
        (repo_root / name).read_text(encoding="utf-8")
        for name in ("AGENTS.md", "README.md", "docs/design.md", ".env.example")
        if (repo_root / name).exists()
    )
    sources = [
        path
        for base, suffix in (
            (repo_root / "src", ".py"),
            (repo_root / "services", ".py"),
            (repo_root / "scripts", ".py"),
            (repo_root / "extension" / "src", ".js"),
        )
        for path in base.rglob(f"*{suffix}")
        if path.is_file()
        and not any(part in {"vendor", "dist", ".build", ".tmp", "__pycache__"} for part in path.parts)
    ]
    read: set[str] = set()
    for path in sources:
        text = path.read_text(encoding="utf-8", errors="ignore")
        for pattern in ENV_READERS:
            read.update(re.findall(pattern, text))
    ours = read - PLATFORM_ENV
    assert len(ours) >= 12, f"only {len(ours)} settings were found; the walk is broken: {sorted(ours)}"
    missing = sorted(name for name in ours if not re.search(rf"\b{re.escape(name)}\b", docs))
    assert not missing, f"settings the code reads but no document names: {missing}"
